const path=require('node:path');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const {chromium}=require(process.env.WALLZ_PLAYWRIGHT || 'playwright');
const root=path.resolve(__dirname,'..');
const opening={pawns:{p1:{x:4,y:0},p2:{x:4,y:8}},walls:[],wallsRemaining:{p1:10,p2:10},turn:'p1',winner:null,variant:'classic'};
const result=(to,score)=>({candidates:[{move:{type:'pawn',to},score,winNow:false,route:[],ownDistance:7,opponentDistance:8}],depth:3,nodes:10,elapsedMs:10,legalCount:131,searchedCount:27});
let browser;
(async()=>{
  browser=await chromium.launch({headless:true,executablePath:process.env.WALLZ_BROWSER_EXECUTABLE || chromium.executablePath()});
  const page=await browser.newPage();
  await page.route('**/*',route=>route.fulfill({contentType:'text/html',body:'<html><body><svg aria-label="Wallz board" width="600" height="600"></svg></body></html>'}));
  await page.goto('https://www.wallz.gg/adviser-test');
  await page.evaluate(()=>{
    window.requests=[];
    window.chrome={runtime:{sendMessage:message=>new Promise(resolve=>requests.push({message,resolve})),onMessage:{addListener:()=>{}}}};
  });
  await page.addScriptTag({path:path.join(root,'extension','rules.js')});
  await page.addScriptTag({path:path.join(root,'extension','overlay.js')});
  const panel=page.locator('#wallz-adviser');
  const send=async(data)=>page.evaluate(data=>window.postMessage({channel:'wallz-adviser-position-v1',data},location.origin),data);
  const practice=state=>({mode:'practice',player:'p1',controllable:true,flipped:true,state});
  const ready=async count=>page.waitForFunction(count=>requests.length===count,count);
  const resolve=async(index,value)=>page.evaluate(({index,value})=>requests[index].resolve({result:value}),{index,value});
  const assertions=[];
  await send(practice(opening));await ready(1);await resolve(0,result(13,-1000));
  await panel.getByText('Losing line found in selective search',{exact:true}).waitFor();
  assert.equal(await panel.getByText('Winning line found in selective search',{exact:true}).count(),0);
  assertions.push('Negative terminal score is labelled as a losing line');
  const next={...opening,pawns:{...opening.pawns,p1:{x:4,y:1}}};
  await send(practice(next));await ready(2);await resolve(1,result(22,1000));
  await panel.getByText('Winning line found in selective search',{exact:true}).waitFor();
  assertions.push('Positive terminal score is labelled as a winning line');
  await send(practice({...next,pawns:{...next.pawns,p1:{x:4,y:2}}}));await ready(3);
  await send(practice({...next,pawns:{...next.pawns,p1:{x:4,y:3}}}));await ready(4);
  await resolve(2,result(31,1000));await page.waitForTimeout(100);
  assert.equal(await panel.locator('.candidate').count(),0);
  await panel.getByText('Considering moves and walls…',{exact:true}).waitFor();
  await resolve(3,result(40,.1));await panel.getByText('Move to e5',{exact:true}).waitFor();
  assertions.push('A delayed result from an older position is discarded');
  await send(practice(next));await ready(5);
  await send({mode:'ranked',reason:'Advice is disabled in ranked games.'});
  await resolve(4,result(22,1000));await page.waitForTimeout(100);
  assert.equal(await panel.locator('.candidate').count(),0);
  await panel.getByText('Advice is disabled in ranked games.',{exact:true}).waitFor();
  assertions.push('Switching to ranked mode clears advice and rejects pending results');
  await send(practice({...opening,turn:'invalid'}));
  await panel.getByText('Position could not be read',{exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>requests.length),5);
  assertions.push('Invalid captured state is rejected before requesting search');
  await send(practice(opening));await ready(6);
  await panel.getByRole('button',{name:'Pause',exact:true}).click();
  await resolve(5,result(13,1000));await page.waitForTimeout(100);
  assert.equal(await panel.locator('.candidate').count(),0);
  await panel.getByText('Analysis paused',{exact:true}).waitFor();
  assertions.push('Pause rejects an in-flight search response');
  await panel.getByRole('button',{name:'Resume',exact:true}).click();await ready(7);
  await page.evaluate(()=>requests[6].resolve({error:'Test worker unavailable'}));
  await panel.getByText('Analysis unavailable',{exact:true}).waitFor();
  assertions.push('Runtime search failures produce a recoverable status');
  // Independently exercise the reader with a small committed React tree fixture.
  const reader=await browser.newPage();
  await reader.route('**/*',route=>route.fulfill({contentType:'text/html',body:'<html><body><svg aria-label="Wallz board"></svg></body></html>'}));
  await reader.goto('https://www.wallz.gg/reader-test');
  await reader.evaluate(state=>{
    const board=document.querySelector('svg');
    const root={stateNode:{}};
    const game={memoizedProps:{snapshot:{game:state,source:'friend-code',ranked:false,status:'playing'}},return:root};
    const component={memoizedProps:{state,controllable:true,bottomPlayer:'p2'},return:game};
    const svg={stateNode:board,return:component};root.child=game;game.child=component;component.child=svg;root.stateNode.current=root;
    board.__reactFiber$fixture=svg;window.fixtureGame=game;window.samples=[];
    window.addEventListener('message',e=>{if(e.data?.channel==='wallz-adviser-position-v1')samples.push(e.data.data);});
  },opening);
  await reader.addScriptTag({path:path.join(root,'extension','bridge.js')});
  await reader.waitForFunction(()=>samples.some(s=>s.mode==='private'));
  assert.equal(await reader.evaluate(()=>samples.at(-1).flipped),false);
  await reader.evaluate(()=>fixtureGame.memoizedProps.snapshot.ranked=true);
  await reader.waitForFunction(()=>samples.at(-1)?.mode==='ranked');
  assert.equal(await reader.evaluate(()=>samples.at(-1).state),undefined);
  await reader.evaluate(()=>{fixtureGame.memoizedProps.snapshot.ranked=false;fixtureGame.memoizedProps.snapshot.source='matchmaking';});
  await reader.waitForFunction(()=>samples.at(-1)?.mode==='unsupported');
  assert.equal(await reader.evaluate(()=>samples.at(-1).state),undefined);
  assertions.push('Reader exposes private positions but excludes ranked and public states');
  const report={status:'PASS',assertions,checkedAt:new Date().toISOString()};
  fs.mkdirSync(path.join(root,'work','browser-evidence'),{recursive:true});
  fs.writeFileSync(path.join(root,'work','browser-evidence','fixtures.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{await browser?.close();});
