const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {chromium}=require(process.env.WALLZ_PLAYWRIGHT||'playwright');
const root=path.resolve(__dirname,'..');
const opening={pawns:{p1:{x:4,y:0},p2:{x:4,y:8}},walls:[],wallsRemaining:{p1:10,p2:10},turn:'p1',winner:null,variant:'classic'};
let browser;
(async()=>{
  browser=await chromium.launch({headless:true,executablePath:process.env.WALLZ_BROWSER_EXECUTABLE||chromium.executablePath()});
  const page=await browser.newPage();page.setDefaultTimeout(5000);
  await page.route('**/*',route=>route.fulfill({contentType:'text/html',body:'<html><body><svg aria-label="Wallz board" viewBox="-44 -22 702 702" width="600" height="600"><rect x="-44" y="-22" width="702" height="702" fill="black"/></svg></body></html>'}));
  await page.goto('https://www.wallz.gg/autogg-fixture');
  await page.evaluate(state=>{
    window.chats=[];window.responses=[];window.samples=[];window.analyses=0;window.chatReply={ok:true};
    window.advice={provenWin:true,nodes:0,candidates:[{move:{type:'pawn',to:13},score:999,bound:'proven',route:[4,13]}]};
    window.chrome={runtime:{sendMessage:async message=>{if(message.type==='WALLZ_ANALYSE'){analyses++;return {result:advice};}return {};},onMessage:{addListener:()=>{}}}};
    const board=document.querySelector('svg'),root={stateNode:{}};
    window.room={code:'ABC123',moves:Array(12).fill({move:{type:'pawn',to:13}}),game:state,status:'playing'};
    window.online={memoizedProps:{snapshot:room,socketConnected:true,onSendChat:text=>{chats.push(text);return Promise.resolve(chatReply);}},return:root};
    window.component={memoizedProps:{state,controllable:true,bottomPlayer:'p1'},return:online};
    const svg={stateNode:board,return:component};root.child=online;online.child=component;component.child=svg;root.stateNode.current=root;
    board.__reactFiber$fixture=svg;
    window.addEventListener('message',event=>{
      if(event.data?.channel==='wallz-adviser-chat-result-v1')responses.push(event.data);
      if(event.data?.channel==='wallz-adviser-position-v1')samples.push(event.data.data);
    });
  },opening);
  for(const file of ['rules.js','overlay.js','bridge.js'])await page.addScriptTag({path:path.join(root,'extension',file)});
  const panel=page.locator('#wallz-adviser');
  await page.locator('#wallz-adviser-overlay [data-action]').waitFor();
  await panel.getByRole('button',{name:'Adviser controls',exact:true}).click();
  const toggle=panel.getByRole('checkbox',{name:'Auto GG',exact:true});
  assert.equal(await toggle.isChecked(),false);assert.equal(await page.evaluate(()=>chats.length),0);
  await toggle.check();await page.waitForFunction(()=>chats.length===1);
  assert.deepEqual(await page.evaluate(()=>chats),['GG']);
  const update=async({count,proven=true,score=999,bound='proven',player='p1',turn='p1',chat=true,reply={ok:true}})=>{
    const before=await page.evaluate(()=>analyses);
    await page.evaluate(({count,proven,score,bound,player,turn,chat,reply})=>{
      chatReply=reply;advice={...advice,provenWin:proven,candidates:[{...advice.candidates[0],score,bound}]};
      room.moves=Array(count).fill({move:{type:'pawn',to:13}});
      room.game={...room.game,pawns:{p1:{x:count%9,y:1},p2:{x:4,y:8}},turn};
      component.memoizedProps={...component.memoizedProps,state:room.game,bottomPlayer:player};
      if(!chat)delete online.memoizedProps.onSendChat;
    },{count,proven,score,bound,player,turn,chat,reply});
    await page.waitForFunction(before=>analyses>before,before);
    await page.waitForTimeout(30);
  };
  await update({count:14});assert.equal(await page.evaluate(()=>chats.length),1);
  await toggle.uncheck();await toggle.check();await page.waitForTimeout(30);
  assert.equal(await page.evaluate(()=>chats.length),1);
  await update({count:0,proven:false,score:-999});assert.equal(await page.evaluate(()=>chats.length),1);
  await update({count:1,proven:false,score:999,bound:'estimate'});assert.equal(await page.evaluate(()=>chats.length),1);
  await update({count:2});await page.waitForFunction(()=>chats.length===2);
  await update({count:0,player:'p2',turn:'p1'});assert.equal(await page.evaluate(()=>chats.length),2);
  await update({count:1,player:'p2',turn:'p2'});await page.waitForFunction(()=>chats.length===3);
  await page.evaluate(()=>window.postMessage({channel:'wallz-adviser-chat-v1',type:'gg',id:901,position:samples.at(-1)},location.origin));
  await page.waitForFunction(()=>responses.some(r=>r.id===901&&r.error==='GG was already sent this game.'));
  await page.evaluate(()=>window.postMessage({channel:'wallz-adviser-chat-v1',type:'gg',id:902,position:samples[0]},location.origin));
  await page.waitForFunction(()=>responses.some(r=>r.id===902&&r.error==='Position changed.'));
  assert.equal(await page.evaluate(()=>chats.length),3);
  await panel.getByRole('button',{name:'Pause',exact:true}).click();
  await page.evaluate(()=>{room.moves=[];room.game={...room.game,turn:'p2',pawns:{p1:{x:4,y:0},p2:{x:4,y:8}}};component.memoizedProps.state=room.game;});
  await page.waitForFunction(()=>samples.at(-1).state.pawns.p1.y===0);
  assert.equal(await page.evaluate(()=>chats.length),3);
  await panel.getByRole('button',{name:'Resume',exact:true}).click();await page.waitForFunction(()=>chats.length===4);
  await update({count:1,player:'p2',turn:'p2'});
  await update({count:0,reply:{ok:false,error:'offline'},player:'p2',turn:'p2'});
  await page.waitForFunction(()=>chats.length===5);
  await panel.getByText('Auto GG: offline',{exact:true}).waitFor();
  await update({count:1,player:'p2',turn:'p2'});assert.equal(await page.evaluate(()=>chats.length),5);
  await update({count:0,chat:false});assert.equal(await page.evaluate(()=>chats.length),5);
  const report={status:'PASS',assertions:['Auto GG is off by default','A proven win sends GG exactly once','Winning estimates and proven losses do not send GG','Rematches reset duplicate protection','The trigger belongs to the local player on either side','Bridge rejects stale and duplicate requests','Pause disables sending and resume restores it','Failed acknowledgements do not cause repeated messages','Games without online chat do not send'],checkedAt:new Date().toISOString()};
  fs.mkdirSync(path.join(root,'work','browser-evidence'),{recursive:true});
  fs.writeFileSync(path.join(root,'work','browser-evidence','autogg.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{await browser?.close();});
